#!/usr/bin/env python3
"""Convert TTF fonts into anti-aliased VLW fonts embedded as C arrays.

LovyanGFX draws VLW fonts with smooth alpha blending, which makes the small
screen look much closer to the original design than the built-in 1-bit fonts.

Usage:  python3 tools/fonts/make_fonts.py   (needs Pillow: pip install pillow)
Output: src/ui/fonts.cpp / src/ui/fonts.h
"""
import os
import struct
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONT_DIR = HERE
OUT_DIR = os.path.join(HERE, "..", "..", "src", "ui")

ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
DEG = "°"

# name, ttf file, pixel size, characters
FONTS = [
    ("font_r8",  "Poppins-Regular.ttf",  8, ASCII + DEG),
    ("font_r9",  "Poppins-Regular.ttf",  9, ASCII + DEG),
    ("font_r10", "Poppins-Regular.ttf", 10, ASCII + DEG),
    ("font_m10", "Poppins-Medium.ttf",  10, ASCII + DEG),
    ("font_m11", "Poppins-Medium.ttf",  11, ASCII + DEG),
    ("font_r13", "Poppins-Regular.ttf", 13, ASCII + DEG),
    ("font_m16", "Poppins-Medium.ttf",  16, ASCII + DEG),
    ("font_l28", "Poppins-Light.ttf",   28, ASCII + DEG),
]


def build_vlw(ttf_path, size, chars):
    font = ImageFont.truetype(ttf_path, size)
    glyphs = []
    for ch in sorted(set(chars), key=ord):
        adv = int(round(font.getlength(ch)))
        if ch == " ":
            glyphs.append((ord(ch), 0, 0, adv, 0, 0, b""))
            continue
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = r - l, b - t
        img = Image.new("L", (max(w, 1), max(h, 1)), 0)
        ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
        glyphs.append((ord(ch), h, w, adv, -t, l, img.tobytes() if w and h else b""))

    ascent = -font.getbbox("d", anchor="ls")[1]
    descent = font.getbbox("p", anchor="ls")[3]
    out = bytearray(struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent))
    for code, h, w, adv, dy, dx, _ in glyphs:
        out += struct.pack(">7i", code, h, w, adv, dy, dx, 0)
    for g in glyphs:
        out += g[6]
    return bytes(out)


def main():
    cpp = ['// Generated by tools/fonts/make_fonts.py from Poppins (SIL Open Font License).',
           '// Do not edit by hand.', '#include "fonts.h"', '']
    hdr = ['// Generated by tools/fonts/make_fonts.py', '#pragma once', '#include <stdint.h>', '']
    for name, ttf, size, chars in FONTS:
        data = build_vlw(os.path.join(FONT_DIR, ttf), size, chars)
        hdr.append(f"extern const uint8_t {name}_vlw[{len(data)}];")
        cpp.append(f"const uint8_t {name}_vlw[{len(data)}] FONT_PROGMEM = {{")
        for i in range(0, len(data), 24):
            cpp.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        cpp.append("};\n")
        print(f"{name:12s} {ttf:22s} {size:3d}px  {len(data):6d} bytes")
    hdr.insert(3, '#if defined(ARDUINO)\n#include <pgmspace.h>\n#define FONT_PROGMEM PROGMEM\n'
                  '#else\n#define FONT_PROGMEM\n#endif\n')
    with open(os.path.join(OUT_DIR, "fonts.h"), "w") as f:
        f.write("\n".join(hdr) + "\n")
    with open(os.path.join(OUT_DIR, "fonts.cpp"), "w") as f:
        f.write("\n".join(cpp))


if __name__ == "__main__":
    main()
